// Чистая логика действий на строке языка (admin «Поддержка языков»).
// Вынесена в node-тестируемый модуль: решение о видимости кнопок — чистое
// условие статусов, а не DOM/React-логика.

// «Активировать» доступна для draft (новая запись) и disabled (повторное
// включение после отключения). Не открывается для будущих неизвестных статусов
// (error/archived/...), чтобы не дать активировать язык в непредусмотренном
// состоянии — backend остаётся источником истины по guard-проверкам.
export function canActivate(status) {
  return status === "draft" || status === "disabled";
}

// «Отключить» — только для активного языка, и НИКОГДА для fallback-локали ru
// (независимо от серверной валидации).
export function canDisable(status, code) {
  return status === "active" && code !== "ru";
}
