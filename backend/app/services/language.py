"""Детекция языка текста (Этап 7 фаза D): кириллица/латиница эвристикой.

Достаточно для разметки source_locale (язык исходного документа): технические
документы — преимущественно проза на одном языке с вкраплениями латинских
идентификаторов (SAP/XML), поэтому порог по доле кириллицы надёжно разделяет
ru/не-ru без LLM.

Внутри латиницы язык различается по МАРКЕРНЫМ буквам: немецкие ä/ö/ü/ß («de»,
08.09.2026) и французские диакритики é/è/à/ç/… («fr», добавлен вместе с fr в
манифест UI). Лимит осознанный: текст без единой маркерной буквы неотличим от
английского и помечается «en» — немецкий и французский без диакритик тоже.
Метка source_locale информационная, на поиск не влияет.
"""
from __future__ import annotations

import re

from app.services.sparse import TOKEN_EXTRA_LETTERS

# Буквы считаются по всему алфавиту токенайзера, а не только по ASCII: иначе
# акцентированные буквы не попадали в `lat`, выпадали из `total` и завышали долю
# кириллицы в смешанном тексте (французский документ с русскими вставками
# уезжал в «ru» тем охотнее, чем больше в нём диакритик).
_CYR_RE = re.compile(r"[\u0400-\u04ff]")
_LAT_RE = re.compile(rf"[a-z{TOKEN_EXTRA_LETTERS}]")

# Маркеры немецкого в нижнем регистре (текст ниже приводится к lower).
_DE_RE = re.compile(r"[äöüß]")
# Маркеры французского: ü/ë/ï/ö намеренно НЕ включены — они общие с немецким и
# решали бы спор в пользу случайного языка. Оставлены однозначно французские
# (в немецком не встречаются вовсе) плюс лигатура œ.
_FR_RE = re.compile(r"[àâçéèêîôùûÿœ]")

# Минимальная доля маркеров среди букв текста. Реальная немецкая проза даёт
# ~1.8% умлаутов+ß, французская — ещё больше, так что 0.5% отсекает вкрапления
# и оставляет запас для технических текстов с длинными ASCII-идентификаторами.
_MARKER_MIN_RATIO = 0.005
# Минимальное ЧИСЛО маркеров. Защищает ровно от одного случая: одиночная
# иностранная фамилия (один-два умлаута) в английском тексте — там доля
# маркеров может быть какой угодно высокой при коротком тексте, и ratio не
# спасает. ИЗВЕСТНЫЙ ЛИМИТ: три и более таких фамилий в коротком тексте
# («Müller, Schröder und Bäcker») всё равно дадут «de» — на длине, ради которой
# метка и считается (source_locale берётся со 100 000 символов документа),
# решает уже ratio, и вкрапления имён его не перебивают.
_MARKER_MIN_HITS = 3


def detect_language(text: str | None, *, min_letters: int = 20) -> str | None:
    """Возвращает 'ru' | 'de' | 'fr' | 'en' | None по составу букв текста."""
    if not text:
        return None
    lowered = text.lower()
    cyr = len(_CYR_RE.findall(lowered))
    lat = len(_LAT_RE.findall(lowered))
    total = cyr + lat
    if total < min_letters:
        return None
    ratio = cyr / total
    if ratio >= 0.6:
        return "ru"
    if ratio <= 0.4:
        de_hits = len(_DE_RE.findall(lowered))
        fr_hits = len(_FR_RE.findall(lowered))
        # Побеждает язык с бо́льшим числом маркеров: ü считается немецким, но
        # французский текст перевешивает его своими é/è/à.
        if de_hits >= fr_hits and _is_marked(de_hits, total):
            return "de"
        if fr_hits > de_hits and _is_marked(fr_hits, total):
            return "fr"
        return "en"
    return None  # смешанный текст — язык не детерминируется


def _is_marked(hits: int, total: int) -> bool:
    return hits >= _MARKER_MIN_HITS and hits / total >= _MARKER_MIN_RATIO
