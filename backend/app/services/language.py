"""Детекция языка исходного документа (`source_locale`, Этап 7 фаза D).

Офлайн статистическая идентификация через `py3langid` (модель поставляется в
пакете, детерминированная, сетевых вызовов нет; BSD-3-Clause). Заменила
эвристику «кириллица/латиница + маркерные буквы» (06.09.2026), которая давала
систематические ложные `de`/`fr` для pt/it/sv/fi/tr/hu и не различала остальные
европейские языки (pl/cs/ro/... падали в `en`).

Возвращает доминирующий язык документа — ISO 639-1 в нижнем регистре (модель
знает 139 языков + класс `zxx` «не язык», ловящий разметку/идентификаторы).
Метка информационная: `documents.source_locale`, в поиске и UI не участвует.

Правила fallback (осознанный гибрид для коротких/сомнительных текстов):
  - пустой/`None` ввод → `None` (текста нет — язык не определён; отсутствие
    текстового слоя сигнализируется отдельно через `problem=no_text_layer`);
  - текста меньше `min_letters` букв → `'en'` (нейтральный fallback, не de/fr);
  - уверенность ниже `_MIN_CONFIDENCE` (модель сама возвращает `und`) либо
    класс `zxx` → `'en'`.

Известный и принятый предел (валидирован smoke-прогоном на реальном корпусе):
скан без OCR, чей текст — только markdown-ссылки на изображения с русскими
подписями, даёт `und` (conf ~0.44) и, следовательно, `'en'`; такой документ
всегда несёт `problem=no_text_layer`, так что неверная метка не вводит в
заблуждение. Порог под этот случай не подгонялся намеренно.
"""
from __future__ import annotations

from py3langid.langid import LanguageIdentifier, MODEL_FILE

# Единственный экземпляр модели на уровне модуля: грузится ОДИН раз при старте
# процесса (~1.2 c: import + from_model_file), `detect_language` его только
# читает (classify — чистое чтение модели, единственный вызов — в
# `pipeline._finalize`). norm_probs=True даёт уверенность в диапазоне 0..1;
# min_confidence ниже порога возвращает `und` (встроенный abstention) вместо
# вранья.
_IDENTIFIER = LanguageIdentifier.from_model_file(
    MODEL_FILE, norm_probs=True, min_confidence=0.90
)

_MIN_CONFIDENCE = 0.90
# Осознанный срез входа классификатора ради скорости: язык устойчив много
# раньше 100k. `pipeline._finalize` режет те же данные до 100_000 символов как
# общий кап сохраняемого текста — пороги независимы и не обязаны совпадать.
_MAX_CHARS = 20_000

# 'und' — уверенность ниже _MIN_CONFIDENCE; 'zxx' — «не язык» (разметка,
# идентификаторы, числа). Оба → нейтральный fallback 'en'.
_UNDETERMINED = frozenset({"und", "zxx"})

# Централизованное приведение кода модели к каноническому ISO 639-1 (нижний
# регистр). Модель уже отдаёт коды в нижнем регистре — карта синонимов пока
# пуста; это единственная точка для будущих переименований (например, макрокод
# 'no' → 'nb'), чтобы правки не расползались по коду.
_ALIASES: dict[str, str] = {}


def _normalize_code(code: str) -> str:
    return _ALIASES.get(code, code)


def detect_language(text: str | None, *, min_letters: int = 20) -> str | None:
    """Доминирующий язык текста (ISO 639-1) либо нейтральный `'en'`/`None`.

    `min_letters` — минимальное число БУКВ (любого алфавита, через
    `str.isalpha()`: кириллица, латиница, греческий и т.п.) для классификации;
    меньше — `'en'`. Ниже порога `_MIN_CONFIDENCE` или класс `zxx` — тоже `'en'`.
    """
    if not text:
        return None
    sample = text[:_MAX_CHARS]
    if sum(ch.isalpha() for ch in sample) < min_letters:
        return "en"
    lang, _confidence = _IDENTIFIER.classify(sample)
    if lang in _UNDETERMINED:
        return "en"
    return _normalize_code(lang)
