"""Диагностические problem-коды документов (documents.problem).

Статус done означает «пайплайн завершился без исключения», но не «документ
полон и ищется». Инцидент 03.09.2026 показал три класса молчаливой
неполноты при зелёном done: 0 концептов (скан-PDF без текстового слоя),
пропущенная индексация чанков и частично спасённые ответы LLM. Код problem
фиксирует причину для UI (янтарный бейдж) и фильтра «Проблемные».

Код — машиночитаемый идентификатор (стабилен для фильтрации/API);
человекочитаемый текст — PROBLEM_MESSAGES, отдаётся рядом (problem_message).
"""
from __future__ import annotations

# LLM не создала концептов, но текстовый слой есть — поиск только по чанкам.
NO_CONCEPTS = "no_concepts"
# Извлечённый текст практически отсутствует (скан без OCR) — концепты и
# полнотекстовый поиск недоступны, нужен OCR или другой источник.
NO_TEXT_LAYER = "no_text_layer"
# Часть чанков сохранена частично после обрезания ответа LLM (salvage) —
# набор концептов может быть неполным, рекомендуется переиндексация.
LLM_PARTIAL_RESULT = "llm_partial_result"
# LLM-классификатор таблиц не дал валидного решения, поэтому применена
# резервная XML-эвристика; это не означает salvage ответа генератора концептов.
LLM_CLASSIFIER_FALLBACK = "llm_classifier_fallback"
# Индексация чанк-точек пропущена (файлы чанков не найдены в бандле) —
# поиск по сырым фрагментам для этого документа недоступен.
INDEX_PARTIAL_FAILURE = "index_partial_failure"

PROBLEM_MESSAGES: dict[str, str] = {
    NO_CONCEPTS: (
        "Не извлечено ни одного концепта: документ ищется только по чанкам. "
        "Проверьте содержимое или переиндексируйте."
    ),
    NO_TEXT_LAYER: (
        "Документ без извлечённого текста (вероятно, скан без OCR): "
        "концепты и полнотекстовый поиск недоступны."
    ),
    LLM_PARTIAL_RESULT: (
        "Часть чанков сохранена частично после обрезания ответа LLM — "
        "возможна неполнота, рекомендуется переиндексация."
    ),
    LLM_CLASSIFIER_FALLBACK: (
        "Классификатор таблиц использовал резервную эвристику — индекс создан, "
        "но часть табличных концептов может быть менее точной или отсутствовать."
    ),
    INDEX_PARTIAL_FAILURE: (
        "Индексация чанков пропущена (нет файлов чанков в бандле) — "
        "поиск по сырым фрагментам недоступен."
    ),
}


def problem_message(code: str | None) -> str | None:
    """Человекочитаемое объяснение по коду (None → None)."""
    if code is None:
        return None
    return PROBLEM_MESSAGES.get(code, code)
