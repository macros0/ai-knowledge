"""Нормализация ссылок на блоки контекста в ответе LLM.

LLM обязана цитировать блоки строго метками [N] (prompts/chat_system.md),
но периодически пишет «блок с ID 2», «в блоке 4» и т.п. Фронтенд рендерит
кликабельные ссылки только по формату [N] — такие формулировки остаются
некликабельными и выглядят как «сломанная ссылка». Здесь они приводятся
к [N] детерминированно: до отдачи клиенту и до записи в историю чата.

N вне диапазона 1..max_index не трогаем: «блоке 3002» или «блок с ID 100»
(номера отсутствий/сообщений) — это не ссылки на блоки контекста.
"""
import re

# «блок с ID 2», «в блоке 4», «блока номер 3», «блок №2», «блоки 2», «блоке 2 и 4»
_BLOCK_REF = re.compile(
    r"блок[а-яё]*(?:\s+с?\s*(?:ID|номер[а-яё]*|№))?\s*№?\s*(\d+)",
    re.IGNORECASE,
)
# Хвост перечисления после уже нормализованной метки: «[2] и 4», «[2], 4»,
# «[2] и блок 4» — цепочки, где «и/запятая + число» остались без слова «блок».
_CHAIN = re.compile(
    r"(\[\d+\])\s*(?:и|,)\s*(?:блок[а-яё]*(?:\s+с?\s*(?:ID|номер[а-яё]*|№))?\s*)?(\d+)\b",
    re.IGNORECASE,
)


def normalize_citations(answer: str, max_index: int) -> str:
    """Приводит формулировки «блок с ID N» / «в блоке N» к меткам [N].

    max_index — число блоков в контексте ответа.
    """
    if not answer or max_index <= 0:
        return answer

    def _sub_block(m: re.Match) -> str:
        n = int(m.group(1))
        return f"[{n}]" if 1 <= n <= max_index else m.group(0)

    def _sub_chain(m: re.Match) -> str:
        n = int(m.group(2))
        return f"{m.group(1)} и [{n}]" if 1 <= n <= max_index else m.group(0)

    out = _BLOCK_REF.sub(_sub_block, answer)
    out = _CHAIN.sub(_sub_chain, out)
    return out
