#!/bin/sh
# Выравнивание прав на /data и сброс привилегий.
#
# /data приходит бинд-маунтом с хоста (см. docker-compose.yml), поэтому его
# владельца задаёт хост: образ не может выставить его заранее, а
# непривилегированный процесс — исправить. Без этого шага свежий
# `git clone && docker compose up` на Linux падает на старте:
#   PermissionError: [Errno 13] Permission denied: '/data/okf_bundles'
#
# Поэтому контейнер стартует под root, чинит владельца точки монтирования и
# СРАЗУ сбрасывает привилегии — само приложение работает под app.
#
# Если контейнер уже запущен не под root (docker run --user, user: в compose),
# ветка пропускается: привилегий на chown нет, и они не нужны — владельца в
# этом случае выбрал оператор.
set -e

if [ "$(id -u)" = "0" ]; then
    # Рекурсивно — только если владелец верхнего уровня не тот: на большом
    # корпусе рекурсивный chown при каждом старте стоил бы секунды.
    if [ "$(stat -c %u /data 2>/dev/null)" != "$(id -u app)" ]; then
        chown -R app:app /data 2>/dev/null || true
    fi
    exec setpriv --reuid=app --regid=app --init-groups "$@"
fi

exec "$@"
